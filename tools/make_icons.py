"""Icons for the CYD screen: Material Design Icons (the set Home Assistant uses) plus a few
composed ones, kept as local SVG files so a build never needs the internet.

  python3 tools/make_icons.py          downloads missing MDI icons into icons/mdi/ (once),
                                       writes the composed icons to icons/ and icons/images.yaml

All icons are white on transparent; the screen colours them (LVGL image recolor).
"""
import os
import re
import sys
import urllib.request

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "icons")
MDI_DIR = os.path.join(OUT, "mdi")
MDI_URL = "https://raw.githubusercontent.com/Templarian/MaterialDesign/master/svg/{}.svg"

MDI = ["solar-power", "home-lightning-bolt-outline", "transmission-tower", "weather-sunny", "wifi",
       "home-assistant", "battery-outline", "battery-alert-variant-outline", "lightning-bolt",
       "weather-night", "weather-sunset-up", "eye-outline", "hand-back-left", "alert",
       "information-outline", "home", "arrow-right-thin", "battery-70", "battery-charging-outline",
       "battery-charging-70", "plus-thick", "minus-thick", "sine-wave", "power-plug-battery"]


def path_of(name):
    p = os.path.join(MDI_DIR, name + ".svg")
    if not os.path.exists(p):
        os.makedirs(MDI_DIR, exist_ok=True)
        data = urllib.request.urlopen(MDI_URL.format(name), timeout=30).read()
        open(p, "wb").write(data)
        print("downloaded", name)
    return re.search(r'<path d="([^"]+)"', open(p).read()).group(1)


def svg(width, parts, extra=""):
    """parts: (mdi name, x, y, scale) placed on a canvas width x 24."""
    g = "".join(f'<path transform="translate({x} {y}) scale({s})" d="{path_of(n)}"/>' for n, x, y, s in parts)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} 24" width="{width}" height="24">'
            f'<g fill="#ffffff">{g}{extra}</g></svg>')


COMPOSED = {
    # where the house gets its power: battery -> home, grid -> home, grid -> battery (charging)
    "path_batt": svg(52, [("battery-70", 0, 0, 1), ("arrow-right-thin", 15, 2, 0.85), ("home", 30, 0, 1)]),
    "path_grid": svg(52, [("transmission-tower", 0, 0, 1), ("arrow-right-thin", 15, 2, 0.85), ("home", 30, 0, 1)]),
    "path_chg": svg(52, [("transmission-tower", 0, 0, 1), ("arrow-right-thin", 15, 2, 0.85),
                         ("battery-charging-70", 30, 0, 1)]),
    # battery charging (bolt + plus) / discharging (minus) / idle, for the middle of the dials
    "batt_plus": svg(24, [("battery-charging-outline", 0, 0, 1), ("plus-thick", 3.8, 8.8, 0.35)]),
    "batt_minus": svg(24, [("battery-outline", 0, 0, 1), ("minus-thick", 7.8, 8.8, 0.35)]),
    # inverter: a box with a sine wave (DC in, AC out)
    "inverter": svg(24, [("sine-wave", 4.5, 4.5, 0.625)],
                    '<rect x="2" y="2" width="20" height="20" rx="3" fill="none" stroke="#ffffff" stroke-width="2"/>'),
}

# image id: (svg file, size)
IMAGES = {
    "ico_path_batt": ("path_batt", (50, 23)),
    "ico_path_grid": ("path_grid", (50, 23)),
    "ico_path_chg": ("path_chg", (50, 23)),
    "ico_batt_plus": ("batt_plus", (26, 26)),
    "ico_batt_minus": ("batt_minus", (26, 26)),
    "ico_batt_idle": ("mdi/battery-outline", (26, 26)),
    "ico_inverter": ("inverter", (18, 18)),
    "ico_ha": ("mdi/home-assistant", (18, 18)),
    "ico_wifi": ("mdi/wifi", (18, 18)),
    "ico_pv": ("mdi/solar-power", (24, 24)),
    "ico_load": ("mdi/home-lightning-bolt-outline", (24, 24)),
    "ico_grid": ("mdi/transmission-tower", (24, 24)),
    "ico_sun": ("mdi/weather-sunny", (24, 24)),
    "ico_empty": ("mdi/battery-outline", (20, 20)),
    "ico_low": ("mdi/battery-alert-variant-outline", (22, 22)),
    "ico_high": ("mdi/lightning-bolt", (22, 22)),
    "ico_night": ("mdi/weather-night", (22, 22)),
    "ico_ovn": ("mdi/weather-sunset-up", (22, 22)),
    "ico_chg": ("mdi/power-plug-battery", (22, 22)),
    "ico_observe": ("mdi/eye-outline", (22, 22)),
    "ico_manual": ("mdi/hand-back-left", (22, 22)),
    "ico_fault": ("mdi/alert", (22, 22)),
    "ico_info": ("mdi/information-outline", (16, 16)),
}


def main():
    for n in MDI:
        path_of(n)
    for name, data in COMPOSED.items():
        open(os.path.join(OUT, name + ".svg"), "w").write(data)
    y = ["# GENERATED by tools/make_icons.py - do not edit. White icons; the screen recolours them."]
    for iid, (f, (w, h)) in IMAGES.items():
        y += [f"- id: {iid}", f"  file: icons/{f}.svg", f"  resize: {w}x{h}", "  type: RGB565",
              "  transparency: alpha_channel"]
    open(os.path.join(OUT, "images.yaml"), "w").write("\n".join(y) + "\n")
    print(f"{len(COMPOSED)} composed icons, {len(IMAGES)} images -> icons/images.yaml")


if __name__ == "__main__":
    sys.exit(main())
