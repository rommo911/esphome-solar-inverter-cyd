"""Generate the controller-core settings from cyd_settings.py (the one settings table):

  components/solar_autopilot/ap_settings.h     struct Settings + metadata table (C++, no ESPHome)
  components/solar_autopilot/settings_keys.py  setting keys for the ESPHome schema

Only the settings the controller uses are taken (not display, LED or forecast-plane settings).
A setting's key is its id without the "n_" / "sw_" prefix: n_cloudy_kwh -> cloudy_kwh.

  python3 tools/gen_autopilot_settings.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from cyd_settings import NUMBERS, SWITCHES  # noqa: E402

OUT = os.path.join(HERE, "..", "components", "solar_autopilot")
NOT_CORE = {"n_fc_interval_h", "n_pv_kwp", "n_pv_tilt", "n_pv_az", "n_bl_min", "n_ldr_dark", "n_ldr_bright",
            "n_led_r", "n_led_g", "n_led_b", "sw_autobl", "sw_touchdbg"}


def key(i):
    for p in ("n_", "sw_"):
        if i.startswith(p):
            return i[len(p):]
    return i


def f(v):
    s = repr(float(v))
    return s + "f"


nums = [n for n in NUMBERS if n[0] not in NOT_CORE]
sws = [s for s in SWITCHES if s[0] not in NOT_CORE]

h = ["// GENERATED by tools/gen_autopilot_settings.py from tools/cyd_settings.py - do not edit",
     "#pragma once", "", "#include <cstdint>", "", "namespace autopilot_core {", "",
     "// X(key, default)", "#define AUTOPILOT_NUMBERS(X) \\"]
h += [f"  X({key(n[0])}, {f(n[6])}) \\" for n in nums]
h += ["", "#define AUTOPILOT_SWITCHES(X) \\"]
h += [f"  X({key(s[0])}, {'true' if s[2] else 'false'}) \\" for s in sws]
h += ["",
      "// All settings, with their defaults. The caller fills it (from its own storage or entities).",
      "struct Settings {",
      "#define AP_NUM(k, d) float k = d;",
      "  AUTOPILOT_NUMBERS(AP_NUM)",
      "#undef AP_NUM",
      "#define AP_SW(k, d) bool k = d;",
      "  AUTOPILOT_SWITCHES(AP_SW)",
      "#undef AP_SW",
      "};", "",
      "enum NumberId : uint8_t {",
      "#define AP_NUM(k, d) N_##k,",
      "  AUTOPILOT_NUMBERS(AP_NUM)",
      "#undef AP_NUM",
      "  NUMBER_COUNT",
      "};", "",
      "enum SwitchId : uint8_t {",
      "#define AP_SW(k, d) S_##k,",
      "  AUTOPILOT_SWITCHES(AP_SW)",
      "#undef AP_SW",
      "  SWITCH_COUNT",
      "};", "",
      "// For a standalone UI or settings store: name, unit, range and step of every number.",
      "struct NumberInfo {",
      "  const char *key, *name, *unit;",
      "  float min, max, step, def;",
      "};",
      "static const NumberInfo NUMBER_INFO[NUMBER_COUNT] = {"]
h += [f'    {{"{key(n[0])}", "{n[1]}", "{n[2]}", {f(n[3])}, {f(n[4])}, {f(n[5])}, {f(n[6])}}},' for n in nums]
h += ["};", "",
      "struct SwitchInfo {",
      "  const char *key, *name;",
      "  bool def;",
      "};",
      "static const SwitchInfo SWITCH_INFO[SWITCH_COUNT] = {"]
h += [f'    {{"{key(s[0])}", "{s[1]}", {"true" if s[2] else "false"}}},' for s in sws]
h += ["};", "",
      "inline float *number_ptr(Settings &s, NumberId id) {",
      "  switch (id) {",
      "#define AP_NUM(k, d) case N_##k: return &s.k;",
      "    AUTOPILOT_NUMBERS(AP_NUM)",
      "#undef AP_NUM",
      "    default: return nullptr;",
      "  }",
      "}", "",
      "inline bool *switch_ptr(Settings &s, SwitchId id) {",
      "  switch (id) {",
      "#define AP_SW(k, d) case S_##k: return &s.k;",
      "    AUTOPILOT_SWITCHES(AP_SW)",
      "#undef AP_SW",
      "    default: return nullptr;",
      "  }",
      "}", "",
      "}  // namespace autopilot_core", ""]
open(os.path.join(OUT, "ap_settings.h"), "w").write("\n".join(h))

p = ["# GENERATED by tools/gen_autopilot_settings.py from tools/cyd_settings.py - do not edit",
     "# setting key -> entity id it is usually bound to (n_<key> / sw_<key>)",
     "NUMBERS = {"]
p += [f'    "{key(n[0])}": "{n[0]}",' for n in nums]
p += ["}", "SWITCHES = {"]
p += [f'    "{key(s[0])}": "{s[0]}",' for s in sws]
p += ["}", ""]
open(os.path.join(OUT, "settings_keys.py"), "w").write("\n".join(p))
print(f"{len(nums)} numbers, {len(sws)} switches -> ap_settings.h, settings_keys.py")
